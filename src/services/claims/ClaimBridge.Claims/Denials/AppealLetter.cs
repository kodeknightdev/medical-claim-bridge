using System.Globalization;
using ClaimBridge.Claims.Application.Clients;
using ClaimBridge.Claims.Data;
using ClaimBridge.Claims.Domain;
using ClaimBridge.Contracts.Reference;
using ClaimBridge.Contracts.ReferenceData;
using QuestPDF.Fluent;
using QuestPDF.Helpers;

namespace ClaimBridge.Claims.Denials;

/// <summary>Appeal letter generated from a fixed template; the provider supplies the argument and enclosures.</summary>
public static class AppealLetter
{
    public const string Template = """
        Re: Request for reconsideration of claim {claimNumber} (payer reference {payerClaimId})

        Patient account: member ending {memberLast4}
        Date(s) of service: {serviceDates}
        Billed amount: {billed}
        Denial reason: CARC {carc} - {carcExplanation}

        {orgName} respectfully requests reconsideration of the denial above.

        {argument}

        We ask that the claim be reprocessed and paid according to the member's benefits. Please contact our billing
        office with any questions.
        """;

    public static string Fill(Appeal appeal, Claim claim, ProvidersClient.OrgInfo org) => Template
        .Replace("{claimNumber}", claim.ClaimNumber)
        .Replace("{payerClaimId}", claim.PayerClaimId ?? "n/a")
        .Replace("{memberLast4}", claim.MemberIdLast4)
        .Replace("{serviceDates}", string.Join(", ", claim.Lines.Select(l => l.ServiceDate).Distinct().Order().Select(d => d.ToString("yyyy-MM-dd"))))
        .Replace("{billed}", claim.TotalCharge.ToString("C", CultureInfo.GetCultureInfo("en-US")))
        .Replace("{carc}", appeal.CarcCode)
        .Replace("{carcExplanation}", AdjustmentReasons.FindCarc(appeal.CarcCode)?.Explanation ?? "see remittance advice")
        .Replace("{orgName}", org.Name)
        .Replace("{argument}", appeal.Argument.Trim());

    public static byte[] Render(Appeal appeal, Claim claim, ProvidersClient.OrgInfo org, DateOnly today)
    {
        var payer = PayerDirectory.Find(claim.PayerId)?.Name ?? claim.PayerId;
        var body = Fill(appeal, claim, org);
        return Document.Create(doc => doc.Page(page =>
        {
            page.Size(PageSizes.Letter);
            page.Margin(54);
            page.DefaultTextStyle(t => t.FontSize(10.5f));
            page.Header().Column(c =>
            {
                c.Item().Text(org.Name).FontSize(14).SemiBold();
                c.Item().Text($"{org.AddressLine1}, {org.City}, {org.State} {org.Zip}  ·  NPI {org.GroupNpi}");
                c.Item().PaddingVertical(8).LineHorizontal(0.5f);
            });
            page.Content().Column(c =>
            {
                c.Item().Text(today.ToString("MMMM d, yyyy", CultureInfo.GetCultureInfo("en-US")));
                c.Item().PaddingTop(10).Text($"{payer}\nAppeals Department");
                c.Item().PaddingTop(10).Text($"Appeal deadline: {appeal.Deadline:yyyy-MM-dd}").Italic();
                c.Item().PaddingTop(14).Text(body);
                if (appeal.Enclosures.Count > 0)
                {
                    c.Item().PaddingTop(12).Text("Enclosures").SemiBold();
                    foreach (var e in appeal.Enclosures) c.Item().Text("• " + e);
                }
                c.Item().PaddingTop(24).Text($"Sincerely,\n\n{appeal.CreatedBy}\n{org.Name} billing office");
            });
            page.Footer().AlignCenter().Text("Generated by claim-bridge (demo, synthetic data)").FontSize(7).FontColor(Colors.Grey.Medium);
        })).GeneratePdf();
    }
}
